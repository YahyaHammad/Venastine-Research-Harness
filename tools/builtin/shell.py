"""
tools/builtin/shell.py

Shell execution tool (ROADMAP §7). Runs commands in the detected shell
(bash on Linux/macOS, PowerShell on Windows) through the sandbox module
(security/sandbox.py).

SANDBOX MODEL (ROADMAP_v2 §46 moved one tier of this):
  Almost everything runs in Docker. The one exception is HOST_READ --
  a read-only command from config.INERT_COMMANDS whose argument
  resolves OUTSIDE the workspace -- which runs as a host subprocess
  because the file it names is one no container can see. It always
  requires approval, and the prompt names the resolved binary.

  INERT (every argument inside the workspace) used to take that same
  host path, on the argument that a read-only command needs no
  isolation. §46 (EP5) moved it into the container: it is the tier the
  gate AUTO-APPROVES, and on Windows `ls`/`cat`/`grep` have no native
  binary, so the host path was resolving them off the user's PATH and
  executing whichever POSIX toolchain some other product had installed.
  Inside the container they are the pinned image's coreutils. It falls
  back to the host when Docker is down, which changes nothing about the
  approval answer (see security/sandbox.containment_for) and is
  reported to the model as `ran_on: "host"`.

  Non-inert commands go through Docker (strong isolation) or the
  explicit subprocess fallback (weak isolation, requires
  ALLOW_INSECURE_SANDBOX_FALLBACK=True).

  EVERY result carries `ran_on` and `tier` (EP4). The human was always
  told where a command would run; the model never was, and it is the
  one that writes the user an answer about the output.

APPROVAL MODEL (ROADMAP_v2 §28):
  config.SHELL_APPROVAL_MODE is the gate -- "always", "tiered" or
  "never" -- and ToolApprovals.shell is the RATCHET above it: True
  forces "always", and can never loosen (D14).

  Under "tiered", the command is classified ONCE
  (security/sandbox.classify_command) into a capability set, and the
  generic rule in security/capability.auto_approved decides. The same
  profile is then handed to run_sandboxed, so the thing that was
  approved is the thing that runs.

  What this replaced: a five-step ladder whose bottom four steps could
  only return False on the shipped config flags, making the whole check
  a pass-through for ToolApprovals.shell. Audit #157 is what that cost
  -- `cat ~/.aws/credentials` classified as "inert", ran on the HOST,
  and was never asked about.

  TOCTOU safety: run() probes Docker once and passes the result to
  run_sandboxed(). If Docker was available during approval but is now
  down, and the fallback would have required approval, run() returns
  an error instead of silently downgrading.

FILE ACCESS:
  The sandbox restricts filesystem access to the workspace (Docker
  volume mount / fallback cwd). Output files generated by sandboxed
  commands appear in the workspace seamlessly.
"""

from __future__ import annotations

import logging
import shutil

from pydantic import BaseModel, Field

import config
from security import capability, posture
from security.capability import UNAVAILABLE, UNCONTAINED, auto_approved
from security.sandbox import (
    HOST_READ,
    INERT,
    SandboxUnavailable,
    _is_inert,
    classify_command,
    containment_for,
    detect_shell,
    is_docker_available,
    run_sandboxed,
)

logger = logging.getLogger(__name__)

# Validated at IMPORT, so a typo in a security setting is a startup
# failure rather than a policy that quietly means something else. Same
# posture as D24's assert_permissions_declared, applied to a value.
#
# It used to say "re-checked per call as well, because a test or a runtime
# edit can change it after this line has run", and that sentence described
# a test seam and an attack in the same breath: `config.SHELL_APPROVAL_MODE
# = "never"` was one attribute assignment, from anywhere in the process,
# and the gate followed it. §40 (UN1) binds the value once into
# `security.posture`, and `_shell_approval_check` reads it from there.
#
# THIS line still reads `config` directly, and deliberately (UN2). It
# validates the CONSTANT A HUMAN WROTE -- a typo check, not a decision --
# and it runs at import, which is before `main()` has folded in the
# command line. Reading the posture here would mark it bound and make
# `apply_cli()` raise on every launch, because importing this module is
# how the registry is built. The rule the guard enforces: **no module may
# read the posture at import time**, pinned by
# test_posture.py::test_no_module_reads_the_posture_at_import.
capability.validate_mode(config.SHELL_APPROVAL_MODE,
                         "config.SHELL_APPROVAL_MODE")

# Compute the shell name once at import time to avoid blocking on
# subprocess probes every time the schema is accessed. On Windows this
# probes pwsh/powershell; a failure falls back to a static label.
try:
    _SHELL_DISPLAY = detect_shell()
except Exception:
    _SHELL_DISPLAY = "auto-detected"


# ---------------------------------------------------------------------------
# ---- Schema ---------------------------------------------------------------
# ---------------------------------------------------------------------------

class ShellParams(BaseModel):
    command: str = Field(
        ...,
        min_length=1,
        description=(
            "Shell command to execute. WHERE it runs depends on its "
            "arguments, and the result tells you which happened: read "
            "`ran_on` before drawing any conclusion about the machine "
            "you are on. A read-only command (ls, cat, grep, etc.) "
            "whose arguments all resolve INSIDE the workspace runs in "
            "the container. The same command with an argument OUTSIDE "
            "the workspace runs ON THE HOST, with the user's own file "
            "access and the host's own PATH -- it is not sandboxed, and "
            "what it reads is the real machine, not the container. "
            "Everything else runs in the container, with the workspace "
            f"mounted at /workspace. Interpreted by {_SHELL_DISPLAY}."
        ),
    )
    rationale: str = Field(
        default="",
        description=(
            "Why you are running this command, right now, in a sentence "
            "or two. Say what you are trying to learn or change and "
            "what it is for -- not what the command does, which the "
            "reader can see. This is shown to the user on the approval "
            "prompt and recorded with the call; it never affects whether "
            "the command is allowed or how it runs."
        ),
    )


TOOL_SCHEMA = {
    "name": "shell",
    "description": (
        "Execute a shell command. Commands run inside a Docker "
        "container with the workspace mounted at /workspace -- EXCEPT "
        "a read-only command with an argument outside the workspace, "
        "which runs on the HOST with the user's own file access "
        "because the container cannot see those files. The result "
        "carries `ran_on` ('container' or 'host') and `tier`; a "
        "command that ran on the host tells you about the user's real "
        "machine, so do not describe its output as the sandbox's. "
        f"Shell: {_SHELL_DISPLAY}. Output is truncated at "
        f"{config.MAX_READ_CHARS} characters."
    ),
    "input_schema": ShellParams.model_json_schema(),
}

# §42 (RA4). ADVERTISED as required, TOLERATED when absent -- and the
# asymmetry is deliberate rather than an oversight to tidy up.
#
# The schema is what the model reads, so `required` is where the ask
# belongs: a rationale nobody asks for is supplied inconsistently, and
# a drift signal with unknown coverage is not a signal. But
# `ShellParams` keeps its default, because approval is obtained BEFORE
# dispatch: a hard requirement would show the user a modal, take their
# yes, and only then fail validation. That is the burn-a-turn class --
# a human decision spent on an outcome already fixed -- and §32 A7
# rejected it for a condition the tool could see, which this is.
#
# So an omission costs nothing and is VISIBLE: the prompt says
# "(none given)", which is itself the observation. A silent gap would
# not be.
TOOL_SCHEMA["input_schema"]["required"] = ["command", "rationale"]


